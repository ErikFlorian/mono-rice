#!/usr/bin/env python3
"""tuigreet in the style of the 'arch-mono' Plymouth theme.

Writes OUT/config.toml (tuigreet) and OUT/vtrgb (Linux VT palette, applied by
setvtrgb before greetd starts). The Arch logo is drawn with the glyphs the
console font (Terminus ter-v24b) has: full block for the body, ▒/░ for
anti-aliased edges and a ░ ring around it that reads as glow.

usage: gen.py OUT_DIR [blocks|classic|outline] [ROWS]
"""
import re, subprocess, sys, tempfile, pathlib
from PIL import Image, ImageFilter

OUT = pathlib.Path(sys.argv[1])
STYLE = sys.argv[2] if len(sys.argv) > 2 else "classic"
ROWS = int(sys.argv[3]) if len(sys.argv) > 3 else 19
OUT.mkdir(parents=True, exist_ok=True)
CELL_W, CELL_H, SS = 12, 24, 4  # Terminus 12x24, supersampling

svg = pathlib.Path("/usr/share/pixmaps/archlinux-logo.svg").read_text()
d = re.search(r'<path d="([^"]+)" fill-rule', svg).group(1)
# logo bbox in svg units (measured by the plymouth generator): x 11.6..244.4, y 12.07..250.5
BX, BY, BW, BH = 11.62, 12.07, 232.8, 238.4
COLS = round(ROWS * CELL_H * BW / BH / CELL_W)
GLOW = 2  # cells of glow around the logo
W, H = (COLS + 2 * GLOW) * CELL_W, (ROWS + 2 * GLOW) * CELL_H
pad_x, pad_y = GLOW * CELL_W * BW / (COLS * CELL_W), GLOW * CELL_H * BH / (ROWS * CELL_H)
doc = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W * SS}" height="{H * SS}" '
       f'viewBox="{BX - pad_x} {BY - pad_y} {BW + 2 * pad_x} {BH + 2 * pad_y}" preserveAspectRatio="none">'
       f'<path d="{d}" fill="#fff" fill-rule="evenodd"/></svg>')
with tempfile.TemporaryDirectory() as td:
    src, dst = pathlib.Path(td, "l.svg"), pathlib.Path(td, "l.png")
    src.write_text(doc)
    subprocess.run(["rsvg-convert", "-o", dst, src], check=True)
    mask = Image.open(dst).convert("RGBA").getchannel("A")

halo = mask.filter(ImageFilter.GaussianBlur(CELL_W * SS * 0.9))
cov = mask.resize((COLS + 2 * GLOW, ROWS + 2 * GLOW), Image.BOX)
glo = halo.resize((COLS + 2 * GLOW, ROWS + 2 * GLOW), Image.BOX)

lines = []
for y in range(ROWS + 2 * GLOW):
    row = ""
    for x in range(COLS + 2 * GLOW):
        c, g = cov.getpixel((x, y)) / 255, glo.getpixel((x, y)) / 255
        if c > 0.62:
            row += "█"
        elif c > 0.30:
            row += "▒"
        elif c > 0.06 or g > 0.16:
            row += "░"
        else:
            row += " "
    lines.append(row)
while lines and not lines[0].strip():
    lines.pop(0)
while lines and not lines[-1].strip():
    lines.pop()
if STYLE != "blocks":
    # the big Arch logos that ship with fastfetch: "arch" (neofetch classic), "arch3" (outline)
    name = {"classic": "arch", "outline": "arch3"}[STYLE]
    raw = subprocess.run(["fastfetch", "-l", name, "-s", "none", "--pipe", "true"],
                         capture_output=True, text=True, check=True).stdout
    lines = [re.sub(r"\$\d", "", l).rstrip() for l in raw.split("\n")]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    indent = min(len(l) - len(l.lstrip()) for l in lines if l.strip())
    lines = [l[indent:] for l in lines]
# same width on every line, so per-line centring keeps the shape
width = max(len(l) for l in lines)
lines = [l.ljust(width) for l in lines]
logo = "\n".join(lines)
(OUT / "logo.txt").write_text(logo + "\n")

# VT palette: slots keep their meaning, tuned to the Plymouth theme
PALETTE = [  # black red green yellow blue magenta cyan white, then bright variants
    (0x00, 0x00, 0x00), (0xd0, 0x45, 0x45), (0x4c, 0xb0, 0x6c), (0xd8, 0xa6, 0x3c),
    (0xd0, 0xd0, 0xd0), (0xa0, 0x6c, 0xd5), (0x9a, 0x9a, 0x9a), (0xc8, 0xc8, 0xc8),
    (0x55, 0x55, 0x55), (0xff, 0x6e, 0x6e), (0x6f, 0xd6, 0x8f), (0xf2, 0xc8, 0x6a),
    (0xf2, 0xf2, 0xf2), (0xc8, 0x9b, 0xff), (0xdc, 0xdc, 0xdc), (0xf2, 0xf2, 0xf2),
]
(OUT / "vtrgb").write_text("\n".join(",".join(str(c[k]) for c in PALETTE) for k in range(3)) + "\n")

(OUT / "config.toml").write_text(f"""# tuigreet in the style of the Plymouth theme "arch-mono" (generated by
# ~/.local/share/tuigreet-arch-mono/gen.py — edit that and regenerate).
# greetd runs: tuigreet --config /etc/tuigreet/config.toml
# Colors are the 16 VT slots; their RGB comes from /etc/tuigreet/vtrgb (setvtrgb,
# run by a greetd drop-in): blue = #d0d0d0 (light grey), darkgray = dim grey.
# Preview without logging out: tuigreet --mock --config /etc/tuigreet/config.toml

[session]
sessions_dirs = ["/usr/share/wayland-sessions"]

[display]
show_time = true
time_format = "%H:%M"
show_title = false
battery = false
align_greeting = "center"
greeting = '''
{logo}
'''

[remember]
username = true
session = true

[secret]
mode = "characters"
characters = "•"

[layout]
width = 46
container_padding = 1
prompt_padding = 1

[layout.widgets.status_bar]
show_reset = false
show_command = false
show_background = false
show_session_status = false

[theme]
border = "black"
container = "black"
greet = "blue"
time = "darkgray"
prompt = "darkgray"
input = "white"
text = "gray"
action = "darkgray"
button = "darkgray"

[background]
kind = "none"
""")
print(f"{STYLE}: logo {width}x{len(lines)} cells")
print(logo)
